// ── Size constants ──────────────────────────────────────────────

/// ML-KEM-768 public key size (FIPS 203)
pub const MLKEM768_PK_SIZE: usize = 1184;
/// ML-KEM-768 secret key size
pub const MLKEM768_SK_SIZE: usize = 2400;
/// ML-KEM-768 ciphertext size
pub const MLKEM768_CT_SIZE: usize = 1088;
/// ML-KEM-768 shared secret size (always 32 bytes)
pub const MLKEM768_SS_SIZE: usize = 32;

/// ML-DSA-65 public key size (FIPS 204)
pub const MLDSA65_PK_SIZE: usize = 1952;
/// ML-DSA-65 secret key size
pub const MLDSA65_SK_SIZE: usize = 4032;
/// ML-DSA-65 signature size
pub const MLDSA65_SIG_SIZE: usize = 3293;

// ── ML-KEM-768 byte-level wrappers around libcrux ───────────────

/// ML-KEM-768 encapsulation key (FIPS 203 `ek`).
#[derive(Clone)]
pub struct MlKem768PublicKey(mlkem768::MlKem768PublicKey);

impl MlKem768PublicKey {
    /// Parse and validate an encapsulation key.
    ///
    /// Validation is FIPS 203 §7.2 (`validate_public_key`): length, modulus and
    /// canonical encoding. It does **not** prove the key was generated by a
    /// conforming implementation — a time-domain key from the retired pure-JS
    /// engine also passes this check.
    pub fn from_bytes(bytes: &[u8]) -> Result<Self, String> {
        let arr: &[u8; MLKEM768_PK_SIZE] = bytes
            .try_into()
            .map_err(|_| format!("ML-KEM public key must be {MLKEM768_PK_SIZE} bytes"))?;
        let pk = mlkem768::MlKem768PublicKey::from(arr);
        if !mlkem768::validate_public_key(&pk) {
            return Err("ML-KEM public key is not a valid FIPS 203 encapsulation key".to_string());
        }
        Ok(Self(pk))
    }

    pub fn as_bytes(&self) -> &[u8; MLKEM768_PK_SIZE] {
        self.0.as_slice()
    }
}

/// ML-KEM-768 decapsulation key (FIPS 203 `dk`).
///
/// Not `ZeroizeOnDrop`: the inner libcrux type exposes no mutable view, so the
/// bytes cannot be wiped through this wrapper. Callers that hold raw key bytes
/// (KeyStore loads) zeroize their own buffers.
#[derive(Clone)]
pub struct MlKem768SecretKey(mlkem768::MlKem768PrivateKey);

impl MlKem768SecretKey {
    pub fn from_bytes(bytes: &[u8]) -> Result<Self, String> {
        let arr: &[u8; MLKEM768_SK_SIZE] = bytes
            .try_into()
            .map_err(|_| format!("ML-KEM secret key must be {MLKEM768_SK_SIZE} bytes"))?;
        // FIPS 203 §7.3 validation needs a ciphertext (it also checks H(ek)),
        // so it runs in mlkem768_decapsulate_bytes where one is available. Here
        // only the encoding length is knowable.
        Ok(Self(mlkem768::MlKem768PrivateKey::from(arr)))
    }

    pub fn as_bytes(&self) -> &[u8; MLKEM768_SK_SIZE] {
        self.0.as_slice()
    }
}

/// ML-KEM-768 ciphertext.
#[derive(Clone)]
pub struct MlKem768Ciphertext(mlkem768::MlKem768Ciphertext);

impl MlKem768Ciphertext {
    pub fn from_bytes(bytes: &[u8]) -> Result<Self, String> {
        let arr: &[u8; MLKEM768_CT_SIZE] = bytes
            .try_into()
            .map_err(|_| format!("ML-KEM ciphertext must be {MLKEM768_CT_SIZE} bytes"))?;
        Ok(Self(mlkem768::MlKem768Ciphertext::from(arr)))
    }

    pub fn as_bytes(&self) -> &[u8; MLKEM768_CT_SIZE] {
        self.0.as_slice()
    }
}

// ── ML-KEM-768 operations ───────────────────────────────────────

fn random_64() -> [u8; 64] {
    let mut seed = [0u8; 64];
    OsRng.fill_bytes(&mut seed);
    seed
}

fn random_32() -> [u8; MLKEM768_SS_SIZE] {
    let mut m = [0u8; MLKEM768_SS_SIZE];
    OsRng.fill_bytes(&mut m);
    m
}

/// Generate an ML-KEM-768 keypair with fresh OS randomness.
pub fn mlkem768_generate() -> (MlKem768PublicKey, MlKem768SecretKey) {
    let kp = mlkem768::generate_key_pair(random_64());
    (
        MlKem768PublicKey(kp.public_key().clone()),
        MlKem768SecretKey(kp.private_key().clone()),
    )
}

/// Deterministic keypair generation, FIPS 203 `KeyGen_internal(d, z)`.
///
/// `d || z` is exactly the 64-byte seed libcrux expects. Exposed for KAT and
/// cross-implementation tests; production code uses [`mlkem768_generate`].
pub fn mlkem768_generate_derand(
    d: &[u8; 32],
    z: &[u8; 32],
) -> (MlKem768PublicKey, MlKem768SecretKey) {
    let mut seed = [0u8; 64];
    seed[..32].copy_from_slice(d);
    seed[32..].copy_from_slice(z);
    let kp = mlkem768::generate_key_pair(seed);
    (
        MlKem768PublicKey(kp.public_key().clone()),
        MlKem768SecretKey(kp.private_key().clone()),
    )
}

/// Encapsulate with fresh OS randomness.
pub fn mlkem768_encapsulate(
    pk: &MlKem768PublicKey,
) -> (MlKem768Ciphertext, [u8; MLKEM768_SS_SIZE]) {
    let (ct, ss) = mlkem768::encapsulate(&pk.0, random_32());
    (MlKem768Ciphertext(ct), ss)
}

/// Encapsulate with caller-supplied randomness (FIPS 203 `Encaps_internal`).
///
/// The caller owns the 32-byte seed. Production paths must not reuse one;
/// this exists for KAT and interop vectors.
pub fn mlkem768_encapsulate_derand(
    pk: &MlKem768PublicKey,
    randomness: [u8; 32],
) -> (MlKem768Ciphertext, [u8; MLKEM768_SS_SIZE]) {
    let (ct, ss) = mlkem768::encapsulate(&pk.0, randomness);
    (MlKem768Ciphertext(ct), ss)
}

/// Decapsulate. Infallible by construction: ML-KEM returns an implicit-rejection
/// value rather than an error for invalid ciphertexts, and that is the correct
/// FIPS 203 behaviour to preserve.
pub fn mlkem768_decapsulate(
    sk: &MlKem768SecretKey,
    ct: &MlKem768Ciphertext,
) -> [u8; MLKEM768_SS_SIZE] {
    mlkem768::decapsulate(&sk.0, &ct.0)
}

/// Byte-level decapsulate for raw keys loaded from the KeyStore.
///
/// Returns `Err` for malformed inputs instead of panicking: a bad key blob in
/// the store must not abort the process (or the Tauri command thread).
pub fn mlkem768_decapsulate_bytes(
    sk: &[u8; MLKEM768_SK_SIZE],
    ct: &[u8; MLKEM768_CT_SIZE],
) -> Result<[u8; MLKEM768_SS_SIZE], String> {
    let sk_typed = MlKem768SecretKey::from_bytes(sk)?;
    let ct_typed = MlKem768Ciphertext::from_bytes(ct)?;
    if !mlkem768::validate_private_key(&sk_typed.0, &ct_typed.0) {
        return Err(
            "ML-KEM secret key is not a valid FIPS 203 decapsulation key for this ciphertext"
                .to_string(),
        );
    }
    Ok(mlkem768_decapsulate(&sk_typed, &ct_typed))
}

/// ML-KEM-768 keypair with secure memory handling
#[derive(Clone, Zeroize, ZeroizeOnDrop)]
pub struct MlKem768KeyPair {
    pub public_key: [u8; MLKEM768_PK_SIZE],
    #[zeroize]
    pub secret_key: [u8; MLKEM768_SK_SIZE],
}

impl MlKem768KeyPair {
    pub fn generate() -> Self {
        let (pk, sk) = mlkem768_generate();
        Self {
            public_key: *pk.as_bytes(),
            secret_key: *sk.as_bytes(),
        }
    }

    pub fn from_bytes(pk: &[u8; MLKEM768_PK_SIZE], sk: &[u8; MLKEM768_SK_SIZE]) -> Self {
        Self {
            public_key: *pk,
            secret_key: *sk,
        }
    }
}

/// ML-KEM-768 encapsulation result
#[derive(Clone)]
pub struct MlKem768Encapsulation {
    pub ciphertext: [u8; MLKEM768_CT_SIZE],
    pub shared_secret: [u8; MLKEM768_SS_SIZE],
}

impl MlKem768Encapsulation {
    pub fn encapsulate(pk: &MlKem768PublicKey) -> Self {
        let (ct, ss) = mlkem768_encapsulate(pk);
        Self {
            ciphertext: *ct.as_bytes(),
            shared_secret: ss,
        }
    }

    pub fn from_bytes(ct: &[u8; MLKEM768_CT_SIZE], ss: &[u8; MLKEM768_SS_SIZE]) -> Self {
        Self {
            ciphertext: *ct,
            shared_secret: *ss,
        }
    }
}

// ── ML-DSA-65 (rustpq) ──────────────────────────────────────────

pub use rustpq::ml_dsa::mldsa65;

/// ML-DSA-65 signing keypair
#[derive(Clone, Zeroize, ZeroizeOnDrop)]
pub struct MlDsa65KeyPair {
    pub public_key: [u8; MLDSA65_PK_SIZE],
    #[zeroize]
    pub secret_key: [u8; MLDSA65_SK_SIZE],
}

impl MlDsa65KeyPair {
    pub fn generate() -> Self {
        let (pk, sk) = mldsa65::generate(&mut OsRng);
        let mut public_key = [0u8; MLDSA65_PK_SIZE];
        let mut secret_key = [0u8; MLDSA65_SK_SIZE];
        public_key.copy_from_slice(pk.as_bytes());
        secret_key.copy_from_slice(sk.as_bytes());
        Self {
            public_key,
            secret_key,
        }
    }

    pub fn sign(&self, message: &[u8], context: &[u8]) -> Result<[u8; MLDSA65_SIG_SIZE], String> {
        let sk = mldsa65::SecretKey::from_bytes(&self.secret_key)
            .map_err(|e| format!("Invalid SK: {e}"))?;
        let sig = mldsa65::sign(&sk, message, context, &mut OsRng)
            .map_err(|e| format!("Sign failed: {e}"))?;
        let mut out = [0u8; MLDSA65_SIG_SIZE];
        out.copy_from_slice(sig.as_bytes());
        Ok(out)
    }

    pub fn verify(
        &self,
        message: &[u8],
        context: &[u8],
        sig: &[u8; MLDSA65_SIG_SIZE],
    ) -> Result<bool, String> {
        let pk = mldsa65::PublicKey::from_bytes(&self.public_key)
            .map_err(|e| format!("Invalid PK: {e}"))?;
        let sig =
            mldsa65::Signature::from_bytes(sig).map_err(|_| "Invalid sig format".to_string())?;
        Ok(mldsa65::verify(&pk, message, context, &sig).is_ok())
    }
}

/// SHA3-256 fingerprint → "XX XX XX XX XX XX XX XX"
pub fn fingerprint(data: &[u8]) -> String {
    let hash = Sha3_256::digest(data);
    hash[..8]
        .iter()
        .map(|b| format!("{:02X}", b))
        .collect::<Vec<_>>()
        .join(" ")
}

/// Validate ML-KEM-768 public key
pub fn is_valid_mlkem768_pk(pk: &[u8]) -> bool {
    MlKem768PublicKey::from_bytes(pk).is_ok()
}

/// Validate ML-KEM-768 ciphertext
pub fn is_valid_mlkem768_ct(ct: &[u8]) -> bool {
    MlKem768Ciphertext::from_bytes(ct).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_mlkem768_roundtrip() {
        let (pk, sk) = mlkem768_generate();
        let (ct, ss1) = mlkem768_encapsulate(&pk);
        let ss2 = mlkem768_decapsulate(&sk, &ct);
        assert_eq!(ss1, ss2);
    }

    #[test]
    fn test_mlkem768_decapsulate_bytes_reports_bad_input() {
        let (pk, sk) = mlkem768_generate();
        let (ct, _) = mlkem768_encapsulate(&pk);
        // Wrong-length inputs are caught before any KEM work, and the good pair
        // still decapsulates (no panic path left).
        let sk_short: &[u8; MLKEM768_SK_SIZE] = &[0u8; MLKEM768_SK_SIZE];
        assert!(MlKem768SecretKey::from_bytes(&sk_short[..32]).is_err());
        assert!(mlkem768_decapsulate_bytes(sk_short, ct.as_bytes()).is_err());
        assert!(mlkem768_decapsulate_bytes(sk.as_bytes(), &[0u8; MLKEM768_CT_SIZE]).is_ok());
    }

    #[test]
    fn test_mlkem768_secret_key_zeroizes() {
        let (_, sk) = mlkem768_generate();
        let mut copy = *sk.as_bytes();
        copy.zeroize();
        assert_eq!(copy, [0u8; MLKEM768_SK_SIZE]);
    }

    #[test]
    fn test_mldsa65_sign_verify() {
        let kp = MlDsa65KeyPair::generate();
        let sig = kp.sign(b"hello", b"context").unwrap();
        assert!(kp.verify(b"hello", b"context", &sig).unwrap());
        assert!(!kp.verify(b"wrong", b"context", &sig).unwrap());
    }

    #[test]
    fn test_fingerprint() {
        let fp = fingerprint(b"test");
        assert_eq!(fp.len(), 23);
    }
}

